// Generates src/visuals/atlas-data.js, the data behind the homepage's Lacuna visual: the Earth's land as evenly
// spaced dots, and the research sites of the Lacuna Atlas (name, place on the globe, kind).
// The sites come from src/lacuna/atlas/sites.js, the same list the Atlas page is built from, so the homepage cannot
// show a site the Atlas does not have. The land comes from the Atlas's own world-atlas TopoJSON.
//   node scripts/lacuna-home.mjs           rewrites the file
//   node scripts/lacuna-home.mjs --check   changes nothing and fails if the file is out of date
//                                          (scripts/assemble-dist.sh runs this, so CI fails on drift)
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// The Atlas's own copies of d3 and topojson-client, so this script adds no dependency. They are browser (UMD)
// builds and this package is an ES module, so each runs in its own context and fills an exports object.
async function umd(file) {
  const module = { exports: {} };
  runInNewContext(await readFile(resolve(root, file), 'utf8'), { module, exports: module.exports });
  return module.exports;
}
const d3 = await umd('lacuna/vendor/d3-7.9.0.min.js');
const topojson = await umd('lacuna/vendor/topojson-client-3.1.0.min.js');

const atlas = resolve(root, 'src/lacuna/atlas');
const { SITES } = new Function(`${await readFile(resolve(atlas, 'sites.js'), 'utf8')}\nreturn { SITES };`)();
const topo = JSON.parse(await readFile(resolve(atlas, 'data/countries-110m.json'), 'utf8'));
const land = topojson.feature(topo, topo.objects.land);

// A Fibonacci lattice spaces N points evenly over the sphere; the ones on land are kept.
const N = 11000, GOLDEN = Math.PI * (3 - Math.sqrt(5));
const points = [];
for (let i = 0; i < N; i++) {
  const y = 1 - (2 * (i + 0.5)) / N;
  const lat = Math.asin(y) * 180 / Math.PI;
  let lon = ((i * GOLDEN * 180 / Math.PI) % 360 + 360) % 360; if (lon > 180) lon -= 360;
  if (d3.geoContains(land, [lon, lat])) points.push(Math.round(lon * 100), Math.round(lat * 100));
}
const bytes = Buffer.from(new Int16Array(points).buffer);

const sites = SITES.map(s => [s.id, s.name, s.lat, s.lon, s.kind === 'lacuna' ? 1 : 0]);
const text = `// Generated by scripts/lacuna-home.mjs from src/lacuna/atlas/sites.js and data/countries-110m.json. Do not edit.
// LAND: ${points.length / 2} points on land, as little-endian Int16 pairs (longitude, latitude) in hundredths of a degree, base64.
// SITES: [id, name, latitude, longitude, kind] for each research site; kind 1 is a Lacuna investigation, 0 an open question.
export const LAND = '${bytes.toString('base64')}';
export const SITES = ${JSON.stringify(sites)};
`;

const out = resolve(root, 'src/visuals/atlas-data.js');
const current = existsSync(out) ? await readFile(out, 'utf8') : null;
if (process.argv.includes('--check')) {
  if (current !== text) { console.error('lacuna-home: src/visuals/atlas-data.js is out of date, run `node scripts/lacuna-home.mjs`'); process.exit(1); }
  console.log('lacuna-home: src/visuals/atlas-data.js up to date');
} else {
  if (current !== text) await writeFile(out, text);
  console.log(`lacuna-home: ${points.length / 2} land points, ${sites.length} sites, ${text.length} bytes${current === text ? ' (up to date)' : ''}`);
}
