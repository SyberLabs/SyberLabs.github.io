// A 3x5 pixel alphabet for signs and labels drawn inside the low-resolution frame.
const G = {
  A: '010101111101101', B: '110101110101110', C: '011100100100011', D: '110101101101110', E: '111100110100111', F: '111100110100100',
  G: '011100101101011', H: '101101111101101', I: '111010010010111', J: '001001001101010', K: '101101110101101', L: '100100100100111',
  M: '101111111101101', N: '110101101101101', O: '010101101101010', P: '110101110100100', Q: '010101101110011', R: '110101110101101',
  S: '011100010001110', T: '111010010010010', U: '101101101101111', V: '101101101101010', W: '101101111111101', X: '101101010101101',
  Y: '101101010010010', Z: '111001010100111',
  0: '111101101101111', 1: '010110010010111', 2: '110001010100111', 3: '110001010001110', 4: '101101111001001', 5: '111100110001110',
  6: '011100110101010', 7: '111001010010010', 8: '010101010101010', 9: '010101011001110',
  '.': '000000000000010', ':': '000010000010000', '-': '000000111000000', '/': '001001010100100', '!': '010010010000010',
  '?': '110001010000010', '+': '000010111010000', "'": '010010000000000', ',': '000000000010100', '>': '100010001010100', '<': '001010100010001',
};
export const textW = (s, scale = 1) => (s.length * 4 - 1) * scale;
export function text(c, s, x, y, color, scale = 1) {
  c.fillStyle = color;
  s = String(s).toUpperCase();
  for (let i = 0; i < s.length; i++) {
    const g = G[s[i]];
    if (g) for (let r = 0; r < 5; r++) for (let k = 0; k < 3; k++) if (g[r * 3 + k] === '1') c.fillRect(x + (i * 4 + k) * scale, y + r * scale, scale, scale);
  }
}
export const textC = (c, s, cx, y, color, scale = 1) => text(c, s, Math.round(cx - textW(s, scale) / 2), y, color, scale);
